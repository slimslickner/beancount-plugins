#!/usr/bin/env python3
"""Materialize ``beancount.ops.pad`` padding into explicit ledger transactions.

When a ``pad`` directive is followed by a failing ``balance`` check, Beancount's
automatic ``pad`` post-plugin synthesizes a padding transaction (flagged ``P``)
to make the check pass. Those transactions only exist at load time; they are not
written to the ledger. This tool finds every pad directive that actually
produced padding, and replaces the ``pad`` directive *in its original source
file* with the equivalent normal transaction(s), so the ledger becomes
explicit.

The top-level ledger is loaded once; because padding transactions carry the
``filename``/``lineno`` of the ``pad`` directive they came from, edits are
applied across any included files.

The balance directives that triggered the pads are left in place: they still
assert, and they now pass against the materialized transactions.

This is a source-rewriting tool. It assumes the ledger is under version control
(use ``--dry-run`` first to preview).

USAGE:
    python scripts/materialize_pads.py ledger.beancount --dry-run
    python scripts/materialize_pads.py ledger.beancount
    python scripts/materialize_pads.py ledger.beancount --narration "Opening balance"
"""

from __future__ import annotations

import argparse
import difflib
import sys
from collections import defaultdict
from pathlib import Path
from typing import NamedTuple

from beancount import loader
from beancount.core import data, flags
from beancount.parser import printer

DEFAULT_NARRATION = "Materialized pad for {account} from {source_account}"


class Summary(NamedTuple):
    """Summary of a materialize run."""

    pads: int
    transactions: int
    files: list[str]
    unused: list[data.Pad]
    load_errors: list[data.BeancountError]


def _group_padding_by_source(
    entries: list[data.Directive],
) -> tuple[dict[tuple[str, int], list[data.Transaction]], list[data.Pad]]:
    """Group synthesized padding transactions by their originating pad location.

    Returns a mapping of ``(filename, lineno)`` to the transactions generated by
    that pad directive, plus the list of pad directives that generated nothing
    (unused pads).
    """
    by_source: dict[tuple[str, int], list[data.Transaction]] = defaultdict(list)
    for entry in entries:
        if isinstance(entry, data.Transaction) and entry.flag == flags.FLAG_PADDING:
            key = (entry.meta["filename"], entry.meta["lineno"])
            by_source[key].append(entry)

    unused: list[data.Pad] = []
    for entry in entries:
        if isinstance(entry, data.Pad):
            key = (entry.meta["filename"], entry.meta["lineno"])
            if key not in by_source:
                unused.append(entry)

    return dict(by_source), unused


def _materialize(txn: data.Transaction, narration_template: str) -> data.Transaction:
    """Convert a padding transaction into a normal transaction."""
    padded_posting = txn.postings[0]
    source_posting = txn.postings[-1]
    units = padded_posting.units

    if units is None:
        raise ValueError(
            f"padding transaction at {txn.meta['filename']}:{txn.meta['lineno']} "
            "has a posting without units"
        )
    if source_posting.account is None:
        raise ValueError(
            f"padding transaction at {txn.meta['filename']}:{txn.meta['lineno']} "
            "has a posting without an account"
        )

    try:
        narration = narration_template.format(
            account=padded_posting.account,
            amount=units.number,
            currency=units.currency,
            source_account=source_posting.account,
            date=txn.date,
        )
    except (KeyError, IndexError, ValueError) as e:
        raise ValueError(f"invalid --narration template: {e}") from e

    meta: dict[str, object] = {}
    postings = [posting._replace(meta=None) for posting in txn.postings]

    return txn._replace(
        flag=flags.FLAG_OKAY,
        narration=narration,
        meta=meta,
        postings=postings,
    )


def _directive_span(lines: list[str], lineno: int) -> tuple[int, int]:
    """Return the ``[start, end)`` line indices of the directive at ``lineno``.

    A directive may be followed by indented metadata lines; those are consumed
    until the next non-indented (or blank) line.
    """
    start = lineno - 1
    if start < 0 or start >= len(lines):
        raise ValueError(f"line {lineno} is out of range")
    end = start + 1
    while end < len(lines):
        stripped = lines[end].rstrip("\r\n")
        if stripped and stripped[0] in (" ", "\t"):
            end += 1
        else:
            break
    return start, end


def _render_block(txns: list[data.Transaction], newline: str) -> list[str]:
    """Render transactions as source lines using the given newline."""
    block: list[str] = []
    for txn in txns:
        rendered = printer.format_entry(txn)
        for line in rendered.splitlines():
            block.append(line + newline)
    return block


def _newline_for(lines: list[str]) -> str:
    for line in lines:
        if line.endswith("\r\n"):
            return "\r\n"
        if line.endswith("\n"):
            return "\n"
    return "\n"


def materialize(
    ledger_path: Path,
    narration_template: str = DEFAULT_NARRATION,
    dry_run: bool = False,
) -> tuple[list[str], Summary]:
    """Rewrite the ledger, replacing pads with materialized transactions.

    Returns ``(diff_chunks, summary)``. Files are written unless ``dry_run``.
    """
    entries, load_errors, _ = loader.load_file(str(ledger_path))

    by_source, unused = _group_padding_by_source(entries)
    if not by_source:
        return [], Summary(0, 0, [], unused, load_errors)

    # filename -> list of (start, end, block_lines)
    edits: dict[str, list[tuple[int, int, list[str]]]] = defaultdict(list)
    transaction_count = 0

    for (filename, lineno), txns in sorted(by_source.items()):
        path = Path(filename)
        text = path.read_text(encoding="utf-8")
        lines = text.splitlines(keepends=True)
        newline = _newline_for(lines)

        start, end = _directive_span(lines, lineno)
        directive_line = lines[start].strip()
        if " pad " not in f" {directive_line} ":
            raise ValueError(
                f"{filename}:{lineno} does not appear to be a pad directive "
                f"(found {directive_line!r}); refusing to edit"
            )

        materialized = [_materialize(txn, narration_template) for txn in txns]
        transaction_count += len(materialized)
        edits[filename].append((start, end, _render_block(materialized, newline)))

    # Apply edits per file, bottom-up so earlier line numbers stay valid.
    new_texts: dict[str, str] = {}
    for filename, file_edits in edits.items():
        text = Path(filename).read_text(encoding="utf-8")
        lines = text.splitlines(keepends=True)
        for start, end, block in sorted(file_edits, key=lambda e: e[0], reverse=True):
            lines[start:end] = block
        new_texts[filename] = "".join(lines)

    diff_chunks: list[str] = []
    for filename, new_text in sorted(new_texts.items()):
        old_text = Path(filename).read_text(encoding="utf-8")
        if new_text == old_text:
            continue
        diff = difflib.unified_diff(
            old_text.splitlines(keepends=True),
            new_text.splitlines(keepends=True),
            fromfile=filename,
            tofile=filename,
        )
        diff_chunks.extend(diff)

    if not dry_run:
        for filename, new_text in new_texts.items():
            Path(filename).write_text(new_text, encoding="utf-8")

    summary = Summary(
        pads=len(by_source),
        transactions=transaction_count,
        files=sorted(new_texts),
        unused=unused,
        load_errors=load_errors,
    )
    return diff_chunks, summary


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Replace pad directives with explicit transactions.",
    )
    parser.add_argument("ledger", type=Path, help="top-level ledger file to process")
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="show the proposed changes without writing them",
    )
    parser.add_argument(
        "--narration",
        default=DEFAULT_NARRATION,
        help=(
            "narration template for materialized transactions; available "
            "placeholders: {account}, {amount}, {currency}, {source_account}, "
            f"{{date}} (default: {DEFAULT_NARRATION!r})"
        ),
    )
    args = parser.parse_args(argv)

    ledger_path = args.ledger
    if not ledger_path.is_file():
        print(f"error: no such file: {ledger_path}", file=sys.stderr)
        return 1

    try:
        diff_chunks, summary = materialize(
            ledger_path,
            narration_template=args.narration,
            dry_run=args.dry_run,
        )
    except (OSError, ValueError) as e:
        print(f"error: {e}", file=sys.stderr)
        return 1

    if diff_chunks:
        sys.stdout.writelines(diff_chunks)

    for pad in summary.unused:
        print(
            f"unused pad (no padding generated): "
            f"{pad.meta['filename']}:{pad.meta['lineno']}",
            file=sys.stderr,
        )

    if not summary.pads:
        print("no pads to materialize", file=sys.stderr)
        return 1

    verb = "would replace" if args.dry_run else "replaced"
    prefix = "dry-run: " if args.dry_run else ""
    print(
        f"{prefix}{verb} {summary.pads} pad(s) with {summary.transactions} "
        f"transaction(s) across {len(summary.files)} file(s)",
        file=sys.stderr,
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
